"""Rebuild the TMLR appendix from its canonical source, without manual drift.

Reconstructed because the old tools/make_tmlr_appendix.py is not present in
the surviving source snapshot. This version keeps standalone floats rather
than reconstructing the historical two-up layout; mathematical content is
preserved and only restated theorem environments/duplicate labels change.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def transform(source):
    assert source.count(r'\begin{document}') == 1
    body=source.split(r'\begin{document}',1)[1].split(r'\end{document}',1)[0]
    body=body.replace(r'\maketitle','',1)
    for label in ('prop:pairing','prop:harvest','cor:noop'):
        count=body.count(r'\label{'+label+'}')
        assert count == 1, (label,count)
        env='corollary' if label.startswith('cor:') else 'proposition'
        pattern=r'\\begin\{'+env+r'\}.*?\\end\{'+env+r'\}'
        def restate(match):
            text=match.group()
            if r'\label{'+label+'}' not in text:
                return text
            return text.replace(r'\begin{'+env+'}',r'\begin{'+env+'x}').replace(r'\end{'+env+'}',r'\end{'+env+'x}').replace(r'\label{'+label+'}','')
        body=re.sub(pattern,restate,body,flags=re.DOTALL)
    # Fit the widest registered five-column tables to TMLR's 6.5-inch text.
    body=body.replace('L{2.5cm}L{1.15cm}L{5.95cm}L{1.9cm}L{3.5cm}',
                      'L{2.0cm}L{1.1cm}L{5.7cm}L{1.6cm}L{3.3cm}')
    body=body.replace('L{2.3cm}L{1.15cm}L{6.55cm}L{1.35cm}L{3.6cm}',
                      'L{2.0cm}L{1.1cm}L{5.9cm}L{1.6cm}L{3.3cm}')
    body=body.replace('L{2.15cm}L{1.0cm}L{6.4cm}L{1.15cm}L{1.0cm}',
                      'L{2.15cm}L{1.2cm}L{8.3cm}L{1.7cm}L{1.0cm}')
    body=body.replace(r'\includegraphics[width=7.0in]',
                      r'\includegraphics[width=\textwidth]')
    body=body.replace(r'\code{PvalueTrainerClothing1M}',
                      r'\code{PvalueTrainer}\allowbreak\code{Clothing1M}')
    return '% GENERATED by scripts/revision_generate_appendix.py; edit paper/appendix.tex.\n'+body.lstrip()

def main():
    source=(ROOT/'paper/appendix.tex').read_text(encoding='utf-8')
    result=transform(source)
    (ROOT/'paper_tmlr/appendix_body.tex').write_text(result,encoding='utf-8')
    print('Generated appendix:',len(result),'characters')

if __name__=='__main__':
    main()
